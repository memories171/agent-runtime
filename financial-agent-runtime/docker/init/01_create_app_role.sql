-- 应用账号：非超级用户，受 RLS 约束；迁移账号 agent 仅用于 Alembic。
CREATE ROLE agent_app LOGIN PASSWORD 'agent_app';
GRANT USAGE, CREATE ON SCHEMA public TO agent_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO agent_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO agent_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO agent_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO agent_app;
